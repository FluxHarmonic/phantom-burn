#!/usr/bin/env node
// skin-data.mjs - compile a skinned mesh's sidecar (sigil-graphics'
// scripts/gltf-to-sgm.mjs writes OUT.sgm.json) and the rig notes
// (models/guard/guard-skin.py writes guard-skin-rig.json) into a Sigil
// library, so the skeleton and the walk are in the game's code on both
// targets and nothing is fetched or parsed at run time.
//
//   node scripts/skin-data.mjs assets/guard/guard-skin.sgm.json \
//        assets/guard/guard-skin-rig.json src/phantom/guard/skin-data.sgl
//
// The library, (phantom guard skin-data), exports:
//   SKIN-LAYOUT     the vertex layout, as make-vertex-layout takes it
//   SKIN-JOINTS     the joints as (phantom guard skin)'s make-skeleton takes
//                   them: (name parent (t) (r) (s) (16 inverse-bind) base-or-#f)
//   SKIN-CLIPS      ((name duration channels) ...), channels as make-clip
//                   takes them: (joint path interpolation (times) (values))
//   SKIN-RIG        the rig notes: an alist (torch_tip (x y z)) ...
// Numbers are written as the shortest decimal that reads back as the same
// float32, which is what the data was.

import fs from "node:fs";
import path from "node:path";

const [sidecarPath, rigPath, outPath] = process.argv.slice(2);
if (!outPath) { console.error("usage: skin-data.mjs SIDECAR.json RIG.json OUT.sgl"); process.exit(2); }
const side = JSON.parse(fs.readFileSync(sidecarPath, "utf8"));
const rig = JSON.parse(fs.readFileSync(rigPath, "utf8"));
if (!side.skeleton) { console.error(`skin-data: ${sidecarPath} has no skeleton`); process.exit(1); }

function num(x) {
  const f = Math.fround(x);
  if (Object.is(f, -0) || f === 0) return "0.0";
  for (let p = 1; p <= 9; p++) {
    const s = f.toPrecision(p);
    if (Math.fround(parseFloat(s)) === f) {
      let t = String(parseFloat(s));
      if (/e/.test(t)) t = parseFloat(s).toFixed(12).replace(/0+$/, "");
      return /[.]/.test(t) ? t : t + ".0";
    }
  }
  return String(f);
}
const list = (xs) => `(${xs.map(num).join(" ")})`;
const str = (s) => JSON.stringify(s);   // a Sigil string literal for plain names

const joints = side.skeleton.joints.map((j) =>
  `    (${str(j.name)} ${j.parent} ${list(j.translation)} ${list(j.rotation)} ${list(j.scale)}\n` +
  `     ${list(j.inverse_bind)}\n     ${j.base ? list(j.base) : "#f"})`);
const clips = side.clips.map((c) =>
  `    (${str(c.name)} ${num(c.duration)}\n     (${c.channels.map((h) =>
    `(${h.joint} ${h.path} ${h.interpolation.toLowerCase()}\n       ${list(h.times)}\n       ${list(h.values)})`).join("\n      ")}))`);
const rigEntries = Object.entries(rig).map(([k, v]) =>
  `    (${k} ${Array.isArray(v) ? list(v) : typeof v === "number" ? num(v) : str(v)})`);

const src = `;;; (phantom guard skin-data) - GENERATED by scripts/skin-data.mjs from
;;; ${path.basename(sidecarPath)} and ${path.basename(rigPath)}; do not edit. Rebuild with
;;; scripts/build-skin. ${side.skeleton.joints.length} joints, ${side.clips.length} clip(s), ${side.vertexCount} vertices,
;;; stride ${side.stride}.

(define-library (phantom guard skin-data)
  (import (sigil core))
  (export SKIN-LAYOUT SKIN-JOINTS SKIN-CLIPS SKIN-RIG)
  (begin
    (define SKIN-LAYOUT '(${side.layout.map(([n, f]) => `(${n} ${f})`).join(" ")}))
    (define SKIN-JOINTS
  '(
${joints.join("\n")}))
    (define SKIN-CLIPS
  '(
${clips.join("\n")}))
    (define SKIN-RIG
  '(
${rigEntries.join("\n")}))))
`;
fs.writeFileSync(outPath, src);
console.log(`skin-data: ${outPath}: ${side.skeleton.joints.length} joints, ${side.clips.map((c) => `${c.name} ${c.channels.length} channels`).join(", ")}, ${src.length} bytes`);
